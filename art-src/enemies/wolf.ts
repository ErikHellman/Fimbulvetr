/** One wolf frame: the body strip over the legs strip, the feet kept on row 29. */
function compose(pal: GridPalette, body: string, legs: string, bodyDy = 0): Raster {
  const r = frame(32);
  const b = grid(pal, body);
  const l = grid(pal, legs);
  paste(r, b, 0, bodyDy);
  paste(r, l, 0, 30 - l.h);
  return r;
}

export function wolf(side: Side, phase: number, pose: WolfPose, coat: Coat): Raster {
  return outline(wolfRaw(side, phase, pose, coat), INK, 1);
}

/** The same frame before its ink outline, for composers that grow or crop it first. */
export function wolfRaw(side: Side, phase: number, pose: WolfPose, coat: Coat): Raster {
  const pal = wolfPalette(coat);
  if (side === 'w') {
    if (pose === 'lunge') return compose(pal, SIDE_LUNGE, SIDE_LUNGE_LEGS, 3);
    if (pose === 'crouch') return compose(pal, SIDE_BODY, SIDE_CROUCH_LEGS, 2);
    if (pose === 'howl') return compose(pal, SIDE_HOWL, SIDE_LEGS[phase] ?? SIDE_LEGS[0] ?? '', 4);
    return compose(pal, SIDE_BODY, SIDE_LEGS[phase] ?? SIDE_LEGS[0] ?? '', phase % 2 === 1 ? 1 : 0);
  }
  const body = side === 'n' ? BACK_BODY : pose === 'howl' ? FRONT_HOWL : FRONT_BODY;
  const legs = side === 'n' ? BACK_LEGS : FRONT_LEGS;
  const dy = pose === 'crouch' ? 2 : pose === 'lunge' ? 3 : pose === 'howl' ? 2 : phase % 2 === 1 ? 1 : 0;
  return compose(pal, body, legs[pose === 'lunge' ? 1 : phase] ?? legs[0] ?? '', dy);
}

/** Every frame of one wolf under its placeholder names. */
export function wolfFrames(art: string, coat: Coat, howl: boolean): DrawnFrame[] {
  const out: DrawnFrame[] = [];
  const add = (anim: string, side: Side, i: number, raster: Raster): void => {
    out.push({ name: `${art}_${anim}_${side}_${i}`, raster, pivot: PIVOT });
    if (side === 'w') out.push({ name: `${art}_${anim}_e_${i}`, raster: mirror(raster), pivot: PIVOT });
  };
  for (const side of ['s', 'w', 'n'] as const) {
    add('idle', side, 0, wolf(side, 0, 'stand', coat));
    add('hurt', side, 0, wolf(side, 2, 'stand', coat));
    for (let i = 0; i < 4; i++) add('walk', side, i, wolf(side, i, 'stand', coat));
    add('tell', side, 0, wolf(side, 0, 'crouch', coat));
    add('tell', side, 1, wolf(side, 2, 'crouch', coat));
    add('lunge', side, 0, wolf(side, 0, 'lunge', coat));
    add('lunge', side, 1, wolf(side, 2, 'lunge', coat));
    if (howl) {
      add('howl', side, 0, wolf(side, 0, 'howl', coat));
      add('howl', side, 1, wolf(side, 2, 'howl', coat));
    }
  }
  return out;
}
