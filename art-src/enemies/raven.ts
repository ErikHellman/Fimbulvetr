const faceless = (text: string): string => text.replace(/[eyk]/g, 'b');

export function raven(side: Side, pose: RavenPose): Raster {
  const r = frame(32);
  const shadow = grid(RAVEN_PAL, pose === 'dive' ? DIVE_SHADOW : SHADOW);
  paste(r, shadow, 0, 30 - shadow.h);
  const text = side === 'w' ? SIDE[pose] : side === 'n' ? faceless(FRONT[pose]) : FRONT[pose];
  paste(r, grid(RAVEN_PAL, text), 0, 0);
  return outline(r, INK, 1);
}

export function ravenFrames(): DrawnFrame[] {
  const out: DrawnFrame[] = [];
  const add = (anim: string, side: Side, i: number, raster: Raster): void => {
    out.push({ name: `enemy_rime_raven_${anim}_${side}_${i}`, raster, pivot: PIVOT });
    if (side === 'w')
      out.push({ name: `enemy_rime_raven_${anim}_e_${i}`, raster: mirror(raster), pivot: PIVOT });
  };
  for (const side of ['s', 'w', 'n'] as const) {
    add('fly', side, 0, raven(side, 'up'));
    add('fly', side, 1, raven(side, 'down'));
    add('tell', side, 0, raven(side, 'spread'));
    add('tell', side, 1, raven(side, 'up'));
    add('dive', side, 0, raven(side, 'dive'));
    add('hurt', side, 0, raven(side, 'hurt'));
  }
  return out;
}
